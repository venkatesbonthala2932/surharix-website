(function () {
  const nodes = Array.from(document.querySelectorAll('[data-i18n]'));
  const english = new Map(nodes.map((el) => [el, el.innerHTML]));  // remember the original English
  const englishTitle = document.title;
  const buttons = document.querySelectorAll('[data-lang]');

  function setLanguage(lang) {
    if (!TRANSLATIONS[lang]) lang = 'en';
    const dict = TRANSLATIONS[lang] || {};
    nodes.forEach((el) => {
      const text = dict[el.dataset.i18n];
      el.innerHTML = text !== undefined ? text : english.get(el);
    });
    document.title = dict['meta.title'] || englishTitle;
    document.documentElement.lang = lang;
    buttons.forEach((b) => b.setAttribute('aria-pressed', String(b.dataset.lang === lang)));
    try { localStorage.setItem('surharix-lang', lang); } catch (e) { /* storage blocked — fine */ }
  }

  buttons.forEach((b) => b.addEventListener('click', () => setLanguage(b.dataset.lang)));

  // Start with: ?lang=te in the link → saved choice → English
  let start = new URLSearchParams(location.search).get('lang');
  if (!start) { try { start = localStorage.getItem('surharix-lang'); } catch (e) { start = null; } }
  if (start && start !== 'en') setLanguage(start);
})();
